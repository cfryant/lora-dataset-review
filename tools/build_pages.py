#!/usr/bin/env python3
"""
Build the static GitHub Pages demo in docs/ from the real app pages + sample_data/.
==================================================================================

    python tools/build_pages.py

Generates (overwrites) these DEMO-ONLY folders; docs/index.html, docs/assets/ and
docs/screenshots/ are hand-maintained and left alone:
    docs/stills/index.html     = stills_review/index.html + <script src="../assets/demo-shim.js">
    docs/stills/manifest.json  clip list + round.json + seed selects (what the server would scan)
    docs/stills/img/<clip>/*.png
    docs/video/index.html      = video_review/index.html + the same shim
    docs/video/manifest.json   clip pairs with fps/frames (parsed by video_review/server.py)
    docs/video/media/{targets,pairs}/*.mp4, docs/video/still/<id>/*.png

The app HTML is copied unchanged apart from the injected shim tag, so re-run this after
editing either app's index.html (CI-free: just commit the result). Pages settings:
Settings -> Pages -> "Deploy from a branch" -> main, folder /docs.
"""
import importlib.util
import json
import os
import re
import shutil

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = os.path.join(REPO, "docs")
SAMPLE = os.path.join(REPO, "sample_data")
# Fixed fake "render time" for the demo so the STALE rule is deterministic: any decision made
# in the browser is newer than this, so it is never treated as stale.
DEMO_MTIME = 1767225600  # 2026-01-01T00:00:00Z


def load_video_server():
    spec = importlib.util.spec_from_file_location("video_server", os.path.join(REPO, "video_review", "server.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def inject(src_html, app, origin):
    """Insert the shim before the app's first inline <script> and a 'generated' comment at the top."""
    note = (f"<!-- GENERATED by tools/build_pages.py from {origin} -- do not edit here.\n"
            f"     DEMO-ONLY: ../assets/demo-shim.js replaces the Python server (localStorage + JSON export). -->\n")
    html = src_html.replace("<!doctype html>\n", "<!doctype html>\n" + note, 1)
    tag = f'<script src="../assets/demo-shim.js" data-app="{app}"></script>\n'
    i = html.index("\n<script>") + 1
    return html[:i] + tag + html[i:]


def fresh(d):
    shutil.rmtree(d, ignore_errors=True)
    os.makedirs(d)


def build_stills():
    out, src = os.path.join(DOCS, "stills"), os.path.join(SAMPLE, "stills")
    fresh(out)
    clips, waiting = [], []
    for name in sorted(os.listdir(src)):
        d = os.path.join(src, name)
        if not os.path.isdir(d):
            continue
        files = sorted(os.listdir(d))
        opts = [{"n": int(m.group(1)), "file": f} for f in files
                if (m := re.match(rf"^{re.escape(name)}_s(\d{{2}})\.png$", f))]
        os.makedirs(os.path.join(out, "img", name))
        for f in files:
            shutil.copy2(os.path.join(d, f), os.path.join(out, "img", name, f))
        if f"{name}_original.png" in files and opts:
            clips.append({"clip": name, "original": f"{name}_original.png", "options": opts})
        else:
            waiting.append(name)
    man = {"app": "stills", "clips": clips, "waiting": waiting,
           "round": json.load(open(os.path.join(src, "round.json"))),
           "seed_selects": json.load(open(os.path.join(src, "selects.json")))}
    json.dump(man, open(os.path.join(out, "manifest.json"), "w"), indent=1)
    html = open(os.path.join(REPO, "stills_review", "index.html"), encoding="utf-8").read()
    open(os.path.join(out, "index.html"), "w", encoding="utf-8").write(
        inject(html, "stills", "stills_review/index.html"))


def build_video():
    vs = load_video_server()
    out, src = os.path.join(DOCS, "video"), os.path.join(SAMPLE, "video_out")
    stills = os.path.join(SAMPLE, "stills")
    fresh(out)
    for sub in ("targets", "pairs"):
        shutil.copytree(os.path.join(src, sub), os.path.join(out, "media", sub))
    # Reuse the real server's scanner so the manifest matches /api/clips exactly.
    vs.OUT, vs.STILLS = src, stills
    vs.TARGETS, vs.SOURCES = os.path.join(src, "targets"), os.path.join(src, "pairs")
    vs.CHOSEN_FILE = os.path.join(src, "chosen_stills.json")
    data = vs.scan_clips()
    for c in data["clips"] + data["incomplete"]:
        for k in ("source", "target"):
            if k in c:
                c[k]["mtime"] = DEMO_MTIME
        if c.get("still"):
            dst = os.path.join(out, "still", c["short"])
            os.makedirs(dst, exist_ok=True)
            shutil.copy2(os.path.join(stills, c["short"], c["still"]["file"]), dst)
    man = {"app": "video", "clips": data["clips"], "incomplete": data["incomplete"],
           "seed_selects": {"demo_002": {"status": "approved", "note": "seeded demo decision",
                                         "updated": "2026-01-02T12:00:00Z"}}}
    json.dump(man, open(os.path.join(out, "manifest.json"), "w"), indent=1)
    html = open(os.path.join(REPO, "video_review", "index.html"), encoding="utf-8").read()
    open(os.path.join(out, "index.html"), "w", encoding="utf-8").write(
        inject(html, "video", "video_review/index.html"))


if __name__ == "__main__":
    build_stills()
    build_video()
    open(os.path.join(DOCS, ".nojekyll"), "w").close()
    print("docs/stills and docs/video rebuilt")
